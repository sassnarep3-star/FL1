def inject(obj, tokens: dict):
    """Replace {{token}} anywhere in a JSON structure with a computed value."""
    if isinstance(obj, str):
        for k, v in tokens.items():
            obj = obj.replace("{{%s}}" % k, str(v))
        return obj
    if isinstance(obj, list):
        return [inject(x, tokens) for x in obj]
    if isinstance(obj, dict):
        return {k: inject(v, tokens) for k, v in obj.items()}
    return obj


