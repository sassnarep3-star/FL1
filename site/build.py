#!/usr/bin/env python3
"""Generate the GitHub Pages site from the registers in data/.

The site is a *rendering* of the data, never a second copy of it. That is a deliberate
architecture decision, not a convenience: the brief requires every table row to carry a
source link and every unconfirmable value to stay blank, and the only way to guarantee
that across sixteen pages is to make the pages impossible to hand-edit without
regenerating them.

Rules the builder enforces as it renders:
  * an unknown source id in any row is a hard error (the build dies, loudly);
  * a row with no sources on a factual page is rendered as `NO SOURCE`, and the
    verifier turns that into a build failure;
  * an empty cell renders as a flagged blank, never as an empty <td> that a reader
    might mistake for "nothing to report";
  * pages marked `editorial` (audit, summary, flags) may state that they are
    internal artefacts rather than cite an external source.

    python3 site/build.py        # write docs/pages/
    python3 site/build.py --check  # fail if docs/pages/ is not a faithful build of data/

Output location is docs/pages/ on purpose: a parallel session built a companion site at
docs/*.html in this repository (see COORDINATION.md). Writing beside it rather than over it
is the coordination protocol in action. The nav gains a 'Companion site' group automatically
once those files exist in the tree, so the published result is one connected dashboard
instead of two islands.
"""

