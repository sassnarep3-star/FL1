def nav_html(pid: str) -> str:
    items = []
    for nav_id in NAV_ORDER:
        label = NAV_LABEL.get(nav_id) or next((p[3] for p in PAGES if p[0] == nav_id), nav_id)
        cur = ' aria-current="page"' if nav_id == pid else ""
        items.append(f'<a href="{esc(nav_id)}.html"{cur}>{label}</a>')  # label may carry entities
    for href, label in COMPANION:
        # a companion link is emitted only if that page exists in this tree, so the
        # build never publishes a broken link to another session's work
        if os.path.exists(os.path.join(DOCS_ROOT, href)):
            items.append(f'<a class="companion" href="../{esc(href)}">{esc(label)}</a>')
    if os.path.exists(os.path.join(DOCS_ROOT, "index.html")):
        items.insert(0, '<a href="../index.html">Site root</a>')
    return "".join(items)


