def esc(x) -> str:
    return html.escape("" if x is None else str(x))


def load(name: str) -> dict:
    with open(os.path.join(DATA, f"{name}.json"), encoding="utf-8") as fh:
        return json.load(fh)


def badge(text: str) -> str:
    t = (text or "").upper().strip()
    if not t:
        return ""
    cls = "b-dim"
    if any(k in t for k in ("DELIVERED", "PASS", "FETCHED", "DONE", "ALLOW", "CRITICAL", "RESOLVED",
                            "WORKING", "MITIGATED")):
        cls = "b-ok"
    elif any(k in t for k in ("BLOCK", "FAIL", "UNVERIFIED", "PROHIBIT", "NEEDS", "REJECT",
                              "NOT-FOUND", "NOT-BUILT", "NOT-ATTEMPTED", "NOT-FETCHED", "STALE",
                              "UNREACHABLE", "INCOMPLETE", "REFUSE")):
        cls = "b-bad"
    elif any(k in t for k in ("IN PROGRESS", "PARTIAL", "SPECIFIED", "HYPOTHESIS", "OPEN", "HOLD",
                              "INDEX-MEANS", "SOFT", "PENDING", "EXCLUDED", "UNCLASSIFIED")):
        cls = "b-warn"
    elif any(k in t for k in ("YES", "HIGH", "MEDIUM", "LINKED", "DIRECTIONAL", "LOW")):
        cls = "b-info"
    return f'<span class="badge {cls}">{esc(t)}</span>'


def render_cell(col: dict, value, sources: dict, row: dict | None = None,
              editorial: bool = False) -> str:
    kind = col.get("render")
    if kind == "srclist":
        ids = value or []
        if not ids:
            # A row may be legitimately unsourced if it says why: a register of our own
            # intentions has no external document to cite. The reason is rendered next to
            # the gap so a reader can see the omission was declared, not overlooked.
            reason = (row or {}).get("no_source_reason")
            if reason:
                return f'<span class="pill" title="{esc(reason)}">no external source — {esc(reason)}</span>'
            return ('<span class="pill">internal artefact — no external source</span>'
                    if editorial else '<span class="unverified">NO SOURCE</span>')
        out = []
        for sid in ids:
            s = sources.get(sid)
            if s is None:
                raise SystemExit(f"FATAL: row references unregistered source id {sid!r}")
            cls = {"FETCHED": "b-ok", "INDEX-MEANS": "b-warn", "LINKED": "b-info",
                   "UNREACHABLE": "b-bad", "FETCHED-VIA-SEARCH-SNIPPET": "b-warn"}.get(
                       s.get("verification", ""), "b-dim")
            out.append(f'<a class="badge {cls}" href="{esc(s["url"])}" rel="noopener" '
                       f'target="_blank" title="{esc(s.get("verification"))}">{esc(sid)}</a>')
        return '<span class="src">' + " ".join(out) + "</span>"
    text = "" if value is None else str(value)
    if kind == "link":
        return f'<a href="{esc(text)}" rel="noopener" target="_blank">{esc(text)}</a>'
    if kind == "badge":
        return badge(text)
    if kind == "list":
        items = value if isinstance(value, (list, tuple)) else ([value] if value else [])
        if not items:
            return '<span class="pill">none</span>'
        return " ".join('<span class="pill">{}</span>'.format(esc(i)) for i in items)
    if kind == "mono":
        return '<span class="meta">{}</span>'.format(esc(text))
    if kind == "blankflag":
        # a value a register promises to fill: blank must read as owed, not as zero
        if text == "":
            return '<span class="unverified">— blank · unverified</span>'
        return esc(text)
    if kind in ("num", "number"):
        if text == "":
            return '<span class="unverified">—</span>'
        return esc(text)
    if text == "":
        return '<span class="unverified">—</span>'
    # Raw HTML is allowed only where a register's column opts in with "html": true, and
    # never on a page built from fetched text. A "<" inside a rule string ("p < 0.05")
    # would otherwise be swallowed by the browser as a tag — which is a real bug this
    # project found in its own first build, and the reason escaping is the default.
    return text if col.get("html") else esc(text)


def normalize_cols(cols: list) -> list[dict]:
    """Accept either [{"key","label","render"}] or the shorthand ["key", ...].

    Registers that need no presentation hints list bare keys; forcing every author to
    write a dict per column is noise, and a silent mismatch here would drop data.
    """
    out = []
    for c in cols or []:
        if isinstance(c, str):
            out.append({"key": c, "label": c.replace("_", " ").title()})
        else:
            out.append(c)
    return out


def render_table(block: dict, sources: dict, caption: str = "", editorial: bool = False) -> str:
    cols = normalize_cols(block.get("columns"))
    rows = block.get("rows", [])
    head = "".join(
        f'<th class="num">{esc(c["label"])}</th>' if c.get("render") in ("num", "number")
        else f"<th>{esc(c['label'])}</th>" for c in cols)
    body = []
    for r in rows:
        tds = "".join(f"<td>{render_cell(c, r.get(c['key']), sources, r, editorial)}</td>"
                      for c in cols)
        body.append(f"<tr>{tds}</tr>")
    tid = (block.get("id") or caption or "t").lower().replace(" ", "").replace(",", "")[:28] or "t"
    filt = ""
    if len(rows) > 6 and any(not c.get("render") for c in cols):
        filt = (f'<div class="filter"><label>Filter <input data-filter="#t-{esc(tid)}" '
                f'placeholder="narrow this table"></label><span class="meta">{len(rows)} rows</span></div>')
    cap = f"<caption>{esc(caption)}</caption>" if caption else ""
    return (f'{filt}<div class="tablewrap"><table id="t-{esc(tid)}">{cap}<thead><tr>{head}</tr></thead>'
            f"<tbody>{''.join(body)}</tbody></table></div>")


