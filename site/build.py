def build() -> dict:
    os.makedirs(os.path.join(DOCS, "assets"), exist_ok=True)
    with open(os.path.join(DOCS, "assets", "dashboard.css"), "w", encoding="utf-8") as fh:
        fh.write(CSS)
    with open(os.path.join(DOCS, "assets", "app.js"), "w", encoding="utf-8") as fh:
        fh.write(JS)

    tokens = stats_tokens()
    sources = {r["src_id"]: r for r in load("sources")["rows"]}
    counts = {"pages": 0, "rows": 0, "no_source_rows": 0, "blank_cells": 0}

    for pid, datafile, title, nav_label, blurb in PAGES:
        doc = inject(load(datafile), tokens)
        editorial = bool(doc.get("editorial"))
        updated = doc.get("updated", "")
        blocks = doc.get("sections") or [{"title": None, "description": None,
                                         "columns": doc.get("columns", []), "rows": doc.get("rows", [])}]
        parts = [f"<h1>{esc(title)}</h1>",
                 f'<p class="lede">{doc.get("description") and esc(doc["description"]) or esc(blurb)}</p>']
        if doc.get("decision_rule"):
            parts.append(f'<div class="warnbox"><b>Decision rule.</b> {esc(doc["decision_rule"])}</div>')
        if doc.get("captured_partial"):
            parts.append(f'<div class="warnbox"><b>Partial capture.</b> {esc(doc.get("capture_note", ""))}</div>')
        for b in blocks:
            if b.get("title"):
                parts.append(f"<h2>{esc(b['title'])}</h2>")
            if b.get("description"):
                parts.append(f'<p class="lede">{esc(b["description"])}</p>')
            if b.get("columns"):
                parts.append(render_table(b, sources, b.get("title") or nav_label, editorial))
                counts["rows"] += len(b.get("rows", []))
            elif b.get("prose"):
                parts.append(f'<div class="card">{esc(b["prose"])}</div>')
        for note in doc.get("notes", []):
            parts.append(f'<div class="card"><p class="lede" style="margin:0">{esc(note)}</p></div>')
        html_out = page(pid, title, nav_label, "\n".join(parts), updated, blurb=blurb)
        with open(os.path.join(DOCS, f"{pid}.html"), "w", encoding="utf-8") as fh:
            fh.write(html_out)
        counts["pages"] += 1
        counts["no_source_rows"] += html_out.count("NO SOURCE")

    # demo page
    demo_body, demo_updated = render_demo(sources)
    with open(os.path.join(DOCS, "demo.html"), "w", encoding="utf-8") as fh:
        fh.write(page("demo", "Engine demo output", "Engine demo", demo_body,
                      demo_updated, blurb="Reproducible output of the verification engine, from "
                                          "synthetic logs and the one real captured dataset."))
    counts["pages"] += 1

    # landing page
    body = landing_body(sources, tokens, counts)
    with open(os.path.join(DOCS, "index.html"), "w", encoding="utf-8") as fh:
        fh.write(page("index", "FL1 · NFL decision system", "Dashboard", body,
                      load("sources").get("updated", ""),
                      blurb="Landing page: verified registers, decision-support tables and the "
                            "line-origination programme for the FL1 repository."))
    counts["pages"] += 1
    counts["tokens"] = tokens
    return counts


